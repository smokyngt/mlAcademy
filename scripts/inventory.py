"""Build docs/SOURCE_INVENTORY.md and generated/pdf-toc.json from the files that actually exist.

Read-only with respect to the source material. Run: python -W ignore scripts/inventory.py
"""
import json
import os
import re
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")
import pymupdf  # noqa: E402

ACADEMY = Path(__file__).resolve().parent.parent
ROOT = ACADEMY.parent
OUT_MD = ACADEMY / "docs" / "SOURCE_INVENTORY.md"
OUT_TOC = ACADEMY / "generated" / "pdf-toc.json"
OUT_TOC.parent.mkdir(exist_ok=True)

SKIP_DIRS = {"node_modules", ".git", "__pycache__", ".venv", "academy", "dist"}


def walk(base: Path):
    for dp, dn, fn in os.walk(base):
        dn[:] = [d for d in dn if d not in SKIP_DIRS]
        for f in fn:
            yield Path(dp) / f


def count(base: Path):
    c = {"md": 0, "py": 0, "ipynb": 0, "pdf": 0, "other": 0}
    for p in walk(base):
        ext = p.suffix.lstrip(".")
        c[ext if ext in c else "other"] += 1
    return c


pdf_info = {}
for pdf in sorted((ROOT / "math").glob("*.pdf")):
    doc = pymupdf.open(pdf)
    toc = [(lvl, title.strip(), page) for lvl, title, page in doc.get_toc() if lvl <= 2]
    first = re.sub(r"\s+", " ", doc[0].get_text()).strip()[:160]
    pdf_info[pdf.name] = {"pages": len(doc), "toc": toc, "firstPage": first}
OUT_TOC.write_text(json.dumps(pdf_info, ensure_ascii=False, indent=1), encoding="utf-8")

phases = sorted(p for p in (ROOT / "ai-engineering-from-scratch" / "phases").iterdir() if p.is_dir())
lines = ["# Source inventory", "", "Generated by `scripts/inventory.py` from files that exist on disk. Nothing here is guessed.", ""]

lines += ["## Top-level directories", "", "| Directory | md | py | ipynb | pdf | other | Used? |", "|---|---|---|---|---|---|---|"]
used = {
    "ai-engineering-from-scratch": "Yes: phases 01-12 and 18 imported as source lessons (docs/en.md + quiz.json + code/).",
    "LLMs-from-scratch": "Yes: main-chapter notebooks (ch01-ch07, appendix A) converted to source lessons.",
    "reasoning-from-scratch": "Yes: chapter notebooks converted to source lessons.",
    "math": "Yes: referenced by section and page from authored lessons (not converted; see PDFs below).",
    "ML_CODE": "Referenced only: personal notebooks and Kaggle work. Not converted (not instructional text).",
    "software engineering": "No: unrelated Fastify project (node_modules + server skeleton).",
    "certification": "No: empty directory.",
}
for d in sorted(p for p in ROOT.iterdir() if p.is_dir() and p.name not in SKIP_DIRS and not p.name.startswith(".")):
    c = count(d)
    lines.append(f"| `{d.name}` | {c['md']} | {c['py']} | {c['ipynb']} | {c['pdf']} | {c['other']} | {used.get(d.name, 'Not reviewed')} |")

lines += ["", "## PDFs in `math/`", ""]
role = {
    "math for ML.pdf": "Deisenroth, Faisal, Ong - *Mathematics for Machine Learning* (Cambridge UP). Primary reference for Stage I-II and PCA/GMM/SVM.",
    "Bishop-Pattern-Recognition-and-Machine-Learning-2006.pdf": "Bishop - *Pattern Recognition and Machine Learning* (2006). Primary reference for probabilistic ML, backprop (5.3), kernels, EM.",
    "Designing Machine Learning Systems.pdf": "Huyen - *Designing Machine Learning Systems* (O'Reilly). Reference for data, evaluation, deployment, monitoring.",
}
for name, info in pdf_info.items():
    r = role.get(name, "French NLP / audio course slides (cours-tal-*, apprentissage audio). Topic-specific; not yet mapped to lessons.")
    lines.append(f"- **{name}** - {info['pages']} pages, {len(info['toc'])} TOC entries (levels 1-2). {r}")
    if not info["toc"]:
        lines.append(f"  - First-page text: `{info['firstPage']}`")

lines += ["", "## ai-engineering-from-scratch phases", "", "| Phase | Lesson dirs | With quiz.json | With docs/en.md | Imported |", "|---|---|---|---|---|"]
IMPORTED = {f"{i:02d}" for i in range(1, 13)} | {"18"}
for ph in phases:
    ls = [d for d in ph.iterdir() if d.is_dir()]
    q = sum((d / "quiz.json").exists() for d in ls)
    m = sum((d / "docs" / "en.md").exists() for d in ls)
    lines.append(f"| {ph.name} | {len(ls)} | {q} | {m} | {'yes' if ph.name[:2] in IMPORTED else 'no'} |")
lines += [
    "",
    "Phases 00 (tooling), 13-17 (tool protocols, agents, infrastructure) and 19 (85 capstones) are outside the",
    "mathematics -> ML -> deep learning -> LLM path requested; they are left as-is and can be enabled in",
    "`scripts/build-catalog.ts` (`IMPORT_PHASES`).",
    "",
    "## Overlap / duplication notes",
    "",
    "- Backpropagation, attention, tokenisation and GPT-from-scratch are each covered by ai-engineering-from-scratch, LLMs-from-scratch and reasoning-from-scratch. Authored lessons are the primary explanation; the others are linked as alternate treatments.",
    "- Linear algebra and calculus appear in Deisenroth ch. 2-5 and ai-engineering-from-scratch phase 01. Authored Stage I lessons cite both.",
    "",
]
OUT_MD.write_text("\n".join(lines), encoding="utf-8")
print("wrote", OUT_MD, "and", OUT_TOC)
